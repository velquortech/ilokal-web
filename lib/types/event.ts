/** A row as stored. `location` is PostGIS and never round-trips through here. */
export interface Event {
  id: string;
  /** null = a platform event authored by an admin. */
  business_id: string | null;
  /** The one offering this event promotes, if any. */
  product_id: string | null;

  name: string;
  description: string | null;
  address: string;
  /**
   * Read-only projections of the PostGIS `location`, generated by the DB.
   * PostgREST hands back `location` itself as WKB hex, which no form can use.
   * Never written — `location` is the source of truth.
   */
  latitude: number | null;
  longitude: number | null;
  image_url: string | null;

  /** Both carry date AND time. */
  starts_at: string;
  ends_at: string;
  /**
   * With `daily_end_time`: the event opens these hours on each day of the run.
   * Both null = it runs continuously from `starts_at` to `ends_at`.
   * `daily_end_time` earlier than `daily_start_time` closes after midnight.
   */
  daily_start_time: string | null;
  daily_end_time: string | null;

  /** The event's own site. */
  link_url: string | null;
  /** Where to buy a ticket. Deliberately separate from `link_url`. */
  ticket_url: string | null;

  status: EventStatus;
  review_note: string | null;
  reviewed_by: string | null;
  reviewed_at: string | null;
  /** Banner order. Admin-only — the trigger zeroes any owner-supplied value. */
  priority: number;

  created_at: string;
  updated_at: string;
  archived_at: string | null;
}

/** The shop an event belongs to, as embedded on a read. */
export interface EventBusinessRef {
  id: string;
  shop_name: string;
  logo_url: string | null;
}

/** The offering an event promotes, as embedded on a read. */
export interface EventProductRef {
  id: string;
  name: string;
  image_url: string | null;
}

/** What every public surface renders. */
export interface EventWithRefs extends Event {
  business: EventBusinessRef | null;
  product: EventProductRef | null;
  /** Present only on `events_nearby` reads. */
  distance_meters?: number;
}

/**
 * The columns `/api/mobile/events*` deliberately withholds.
 *
 * `review_note` is an admin's rejection text about an unpublished proposal,
 * `reviewed_by` is an `auth.users` id, and `priority` is internal banner
 * placement. RLS is row-level and cannot express this, so the projection does
 * — see `MOBILE_EVENT_SELECT` in `app/api/helpers/mobileEvent.ts`, which is
 * the runtime half of this type.
 */
export type PrivateEventColumn =
  | 'review_note'
  | 'reviewed_by'
  | 'reviewed_at'
  | 'priority';

/**
 * Exactly what every `/api/mobile/events*` route returns.
 *
 * Written as an `Omit` of `Event` rather than a fresh field list so the two
 * cannot drift: this IS `EventWithRefs` minus the review flow and `priority`,
 * which is precisely how the mobile repo's own `MobileEventWithRefs`
 * (`types/events.ts`) describes itself.
 *
 * `distance_meters` is optional here because only the nearby feed carries it —
 * see `MobileNearbyEvent`, which makes it required.
 */
export interface MobileEventWithRefs extends Omit<Event, PrivateEventColumn> {
  business: EventBusinessRef | null;
  product: EventProductRef | null;
  distance_meters?: number;
}

/** One row of `GET /api/mobile/events/nearby`. */
export type MobileNearbyEvent = MobileEventWithRefs & {
  distance_meters: number;
};

/**
 * One row of the `events_nearby` RPC ITSELF — a flat, deliberately narrow
 * projection, not what the mobile endpoint returns.
 *
 * The RPC does the one thing only PostGIS can do (rank by distance) and the
 * route hydrates those ids through `MOBILE_EVENT_SELECT`, so this shape stops
 * at the route boundary. Widening the RPC to carry the whole event would spell
 * the mobile column list out a second time, in SQL, where it drifts.
 */
export interface NearbyEvent {
  id: string;
  name: string;
  description: string | null;
  address: string;
  // No latitude/longitude here: `events_nearby` does not project them, and a
  // type that claims columns the RPC never returns is worse than no type.
  image_url: string | null;
  starts_at: string;
  ends_at: string;
  daily_start_time: string | null;
  daily_end_time: string | null;
  distance_meters: number;
  business_id: string | null;
  business_name: string | null;
}

/**
 * Counts for the dashboard stat cards, one per status plus the total.
 *
 * `failed` is not decoration: four confident zeros and "we couldn't read this"
 * look identical on a stat card, and this repo has already shipped that
 * confusion once. `staff_picks` is admin-only — the number
 * of platform events (`business_id IS NULL`) — and stays 0 on the owner's side.
 */
export interface EventStats {
  total: number;
  draft: number;
  pending_review: number;
  approved: number;
  rejected: number;
  staff_picks: number;
  failed: boolean;
}

