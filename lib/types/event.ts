/**
 * Event Domain Types
 *
 * An event is the one thing in this app with a DATE. Shops, offerings and
 * deals are ambient; an event starts and stops, which is why it carries a span
 * and an optional daily window rather than a single timestamp.
 *
 * Two authors share the table: `business_id === null` is a platform event an
 * admin wrote, anything else is a shop's proposal. `status` is decided by a DB
 * trigger, never by a client — see `20260802034107_events.sql`.
 */

/** Runtime mirror of the `events.status` CHECK. */
export type EventStatus = 'draft' | 'pending_review' | 'approved' | 'rejected';

